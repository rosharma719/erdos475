"""Python 3.10+. Verify the two-block lemma for every prime 2r+1 with r <= 30.

Only positive witnesses are needed. Generate every zero-sum five-set and
quotient by dilation, then check the graceful paths and block sums directly.
"""

from functools import lru_cache
from itertools import accumulate, combinations, permutations
from math import isqrt


def prime(p):
    return p >= 2 and all(p % i for i in range(2, isqrt(p) + 1))


def mask(values):
    return sum(1 << value for value in values)


def hole_orbits(p):
    index = {}
    representatives = []
    for four in combinations(range(1, p), 4):
        last = -sum(four) % p
        if last <= four[-1]:
            continue
        holes = (*four, last)
        if mask(holes) in index:
            continue
        number = len(representatives)
        representatives.append(holes)
        for factor in range(1, p):
            index[mask(factor * h % p for h in holes)] = number
    return index, representatives


def cycle_labels(alpha, p):
    r = (p - 1) // 2
    assert sorted(alpha) == list(range(1, r + 1))
    delta = [y - x for x, y in zip(alpha, alpha[1:])]
    assert sorted(map(abs, delta)) == list(range(1, r))
    labels = [v % p for v in [*delta, r, *(-v for v in reversed(delta)), -r]]
    assert sorted(labels) == list(range(1, p))
    return labels


def covered_orbits(alpha, p, index):
    labels = cycle_labels(alpha, p)
    doubled = labels * 2
    windows = {}
    for length in (2, 3, 4, 5):
        records = []
        for start in range(len(labels)):
            block = doubled[start:start + length]
            records.append((mask(block), sum(block) % p))
        windows[length] = records
    for short in (2, 3):
        for first, b in windows[short]:
            for second, a in windows[7 - short]:
                if first & second or not (first & (1 << a) and second & (1 << b)):
                    continue
                holes = (first | second) ^ (1 << a) ^ (1 << b)
                yield index[holes]


def check_single_window_obstruction():
    p, r = 29, 14
    holes = (1, 3, 11, 17, 26)
    prefixes = set()
    for factor in range(1, p):
        scaled = {factor * h % p for h in holes}
        for extra in range(1, p):
            if extra in scaled:
                continue
            for order in permutations((*scaled, extra)):
                for j, bridge in enumerate(order):
                    if bridge not in (r, p - r):
                        continue
                    left = tuple(-v % p for v in reversed(order[:j]))
                    right = order[j + 1:]
                    shared = min(len(left), len(right))
                    if left[:shared] != right[:shared]:
                        continue
                    arm = max((left, right), key=len)
                    steps = tuple(v if v <= r else v - p for v in arm)
                    lengths = set(map(abs, steps))
                    if r not in lengths and len(lengths) == len(steps):
                        prefixes.add(steps)

    @lru_cache(maxsize=None)
    def can_finish(vertex, used, lengths):
        if used.bit_count() == r:
            return True
        for dest in range(r):
            step = 1 << abs(dest - vertex)
            if used & (1 << dest) or lengths & step:
                continue
            if can_finish(dest, used | (1 << dest), lengths | step):
                return True
        return False

    placements = 0
    for steps in prefixes:
        offsets = list(accumulate(steps, initial=0))
        if len(set(offsets)) != len(offsets):
            continue
        for start in range(-min(offsets), r - max(offsets)):
            placements += 1
            used = mask(start + v for v in offsets)
            lengths = mask(abs(step) for step in steps)
            assert not can_finish(start + offsets[-1], used, lengths)
    assert (len(prefixes), placements) == (1776, 142)
    print(f"p=29 single window: {len(prefixes)} prefixes, {placements} placements, 0 completions")
    alpha = (8, 13, 1, 14, 3, 10, 6, 5, 11, 2, 12, 4, 7, 9)
    labels = cycle_labels(alpha, p) * 2
    short, long = labels[27:30], labels[13:17]
    assert (short, long) == ([15, 5, 17], [14, 27, 26, 8])
    a, b = sum(long) % p, sum(short) % p
    assert a in short and b in long and set(short).isdisjoint(long)
    assert (set(short) | set(long)) - {a, b} == {5 * h % p for h in holes}


def verify(witnesses):
    W = (1, 3, 7, -2, -4, -5)
    assert len(set(map(abs, W))) == 6 and sum(W) == 0
    assert prime(1009) and (1009 - 1) // 2 == 504
    check_single_window_obstruction()
    for r in range(1, 31):
        p = 2 * r + 1
        if not prime(p):
            continue
        index, representatives = hole_orbits(p)
        seen = set()
        for alpha in witnesses.get(r, ()):
            seen.update(covered_orbits(alpha, p, index))
        paired = sum(any(p - h in H for h in H) for H in representatives)
        print(f"r={r:2} p={p:2} sets={len(index):6} orbits={len(representatives):4} "
              f"paired={paired:3} certified={len(seen):4}", flush=True)
        assert len(seen) == len(representatives), [H for i, H in enumerate(representatives) if i not in seen][:3]


